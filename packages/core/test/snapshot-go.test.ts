import { cpSync, lstatSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { beforeAll, describe, expect, it } from 'vitest';
import { buildSnapshot, initDataDir, loadConfig, sha1, Store } from '../src/index.js';
import type { BuildSnapshotResult, DataDirLayout, ExtractedFile, FileRow, Resolver, SymbolRow } from '../src/index.js';
import { GoResolver } from '../src/resolve/go.js';
import { LanguageResolver } from '../src/resolve/language-resolver.js';
import { ScipPythonResolver } from '../src/resolve/scip-python.js';
import { snapshotDir } from '../src/store/data-dir.js';
import { extractWithCache, type HashedSource } from '../src/snapshot/incremental.js';
import { commitAll, git, tempDir } from './helpers/git-repo.js';

const FIXTURE = path.join(import.meta.dirname, 'fixtures', 'go-basic');
const PKG = 'example.com/gobasic/internal/order';

function fixtureRepo(): string {
  const repo = tempDir('ci-go-fixture-');
  cpSync(FIXTURE, repo, { recursive: true });
  git(repo, 'init', '-q', '-b', 'main');
  commitAll(repo, 'init');
  return repo;
}

describe('snapshot build of a Go repository', () => {
  let repo: string;
  let store: Store;
  let layout: DataDirLayout;
  let build: () => Promise<BuildSnapshotResult>;
  let first: BuildSnapshotResult;
  let files: Map<string, FileRow>;
  let symbols: SymbolRow[];

  beforeAll(async () => {
    repo = fixtureRepo();
    const config = await loadConfig(repo, { dataDir: tempDir('ci-go-data-') });
    layout = await initDataDir(config.dataDir);
    store = new Store(layout.dbPath);
    // Go 固定走名称匹配，结果不受本机有没有 scip-go 影响
    const resolver = () => new LanguageResolver({ python: new ScipPythonResolver(), go: new GoResolver({ scip: false }) });
    build = () => buildSnapshot({ repo, store, layout, config, resolver: resolver() });
    first = await build();
    files = new Map(store.getFiles(first.snapshot.id).map((f) => [f.path, f]));
    symbols = store.getSymbols(first.snapshot.id);
  }, 120_000);

  it('stores Go method, struct and interface method symbols', () => {
    expect(first.snapshot.extractStatus).toBe('ok');
    const byQn = new Map(symbols.map((s) => [`${s.kind} ${s.qualifiedName}`, s]));
    const svc = byQn.get(`class ${PKG}.Service`)!;
    expect(byQn.get(`method ${PKG}.Service.Create`)).toMatchObject({ path: 'backend/internal/order/service.go', parentId: svc.id });
    const repoIface = byQn.get(`interface ${PKG}.Repo`)!;
    expect(byQn.get(`method ${PKG}.Repo.Find`)!.parentId).toBe(repoIface.id);
    expect(byQn.get(`method ${PKG}.Repo.Save`)!.parentId).toBe(repoIface.id);
    expect(byQn.get('function summarize')?.path).toBe('report.py');
    expect(first.snapshot.edgeSources?.go).toMatchObject({ source: 'name_match', reason: 'disabled' });
  });

  it('classifies test, generated and vendored Go files', () => {
    expect(files.get('backend/internal/order/service_test.go')).toMatchObject({ language: 'go', supportLevel: 'full', isTest: true });
    expect(files.get('backend/internal/order/order.pb.go')).toMatchObject({ supportLevel: 'full', isGenerated: true });
    expect(files.get('backend/internal/order/service.go')).toMatchObject({ isTest: false, isGenerated: false });
    expect(files.get('backend/vendor/example.com/dep/dep.go')).toMatchObject({ language: 'go', supportLevel: 'none' });
    expect(symbols.some((s) => s.path.includes('/vendor/'))).toBe(false);
    expect(files.get('report.py')).toMatchObject({ language: 'python', supportLevel: 'full' });
  });

  it('stores Go entries for func main and net/http routes, and Go data models', () => {
    const byId = new Map(symbols.map((s) => [s.id, s]));
    const entries = store.getEntries(first.snapshot.id).map((e) => ({ ...e, qn: byId.get(e.symbolId)?.qualifiedName }));
    expect(entries).toContainEqual(expect.objectContaining({ kind: 'cli', framework: 'go', qn: 'example.com/gobasic/cmd/server.main' }));
    expect(entries).toContainEqual(expect.objectContaining({
      kind: 'http', framework: 'net/http', detail: { path: '/orders' }, qn: 'example.com/gobasic/cmd/server.main.func1',
    }));
    const models = new Map(symbols.filter((s) => s.modelKind).map((s) => [s.qualifiedName, s.modelKind]));
    expect(models.get(`${PKG}.Order`)).toBe('gorm');
    expect(models.get(`${PKG}.Summary`)).toBe('json');
  });

  it('places go.mod and vendored Go files into the snapshot directory', () => {
    const dir = snapshotDir(layout, first.snapshot.contentKey);
    expect(readFileSync(path.join(dir, 'backend/go.mod'), 'utf8')).toContain('module example.com/gobasic');
    expect(statSync(path.join(dir, 'backend/vendor/example.com/dep/dep.go')).isFile()).toBe(true);
  });

  it('marks Go files generated by their header and copies go.mod instead of linking it', async () => {
    writeFileSync(path.join(repo, 'backend/internal/order/zz_mock.go'), '// Code generated by mockgen. DO NOT EDIT.\n\npackage order\n');
    const second = await build();
    expect(second.snapshot.id).not.toBe(first.snapshot.id);
    const row = store.getFiles(second.snapshot.id).find((f) => f.path === 'backend/internal/order/zz_mock.go');
    expect(row).toMatchObject({ isGenerated: true });
    const dir = snapshotDir(layout, second.snapshot.contentKey);
    expect(lstatSync(path.join(dir, 'backend/go.mod')).nlink).toBe(1);
    expect(lstatSync(path.join(dir, 'backend/internal/order/service.go')).nlink).toBeGreaterThan(1);
  }, 120_000);

  it('reads Go extraction results back from the extract cache with the go field', async () => {
    const rels = ['backend/cmd/server/main.go', 'backend/internal/order/service.go'];
    const sources: HashedSource[] = rels.map((rel) => {
      const source = readFileSync(path.join(repo, rel), 'utf8');
      return { path: rel, language: 'go', source, isTest: false, isGenerated: false, contentHash: sha1(source) };
    });
    const ctx = { goModules: new Map([['backend', 'example.com/gobasic']]) };
    await extractWithCache(store, sources, undefined, ctx);
    const again = await extractWithCache(store, sources, undefined, ctx);
    expect(again.cacheHits).toBe(2);
    const main = again.files.find((f) => f.path === 'backend/cmd/server/main.go')!;
    expect(Object.keys(main.go!.imports).length).toBeGreaterThan(0);
    expect(main.go!.calls.find((c) => c.name === 'Create')!.receiverType).toBe(`${PKG}.Service`);
    const moved = await extractWithCache(store, sources, undefined, { goModules: new Map([['backend', 'example.com/other']]) });
    expect(moved.cacheHits).toBe(0);
    expect(moved.files[0]!.go!.packagePath).toBe('example.com/other/cmd/server');
  });
});

describe('retrying resolve on a Go snapshot', () => {
  it('restores Go files with the go field rebuilt from the snapshot go.mod', async () => {
    const repo = fixtureRepo();
    const config = await loadConfig(repo, { dataDir: tempDir('ci-go-data-') });
    const layout = await initDataDir(config.dataDir);
    const store = new Store(layout.dbPath);
    const seen: ExtractedFile[][] = [];
    const resolver = (fail: boolean): Resolver => ({
      name: 'capture', version: '1',
      resolve: async (input) => {
        seen.push(input.files);
        if (fail) throw new Error('boom');
        return { edges: [] };
      },
    });
    const first = await buildSnapshot({ repo, store, layout, config, ref: 'HEAD', resolver: resolver(true) });
    expect(first.snapshot.resolverStatus).toBe('failed');
    const retried = await buildSnapshot({ repo, store, layout, config, ref: 'HEAD', resolver: resolver(false) });
    expect(retried.resolveRetried).toBe(true);
    const pick = (files: ExtractedFile[]) => files.find((f) => f.path === 'backend/cmd/server/main.go')!;
    const [extracted, restored] = [pick(seen[0]!), pick(seen[1]!)];
    expect(restored.go).toEqual(extracted.go);
    expect(restored.go!.packagePath).toBe('example.com/gobasic/cmd/server');
    const methods = (files: ExtractedFile[]) => files.flatMap((f) => f.symbols).filter((s) => s.kind === 'method').map((s) => `${s.id}>${s.parentId}`).sort();
    expect(methods(seen[1]!)).toEqual(methods(seen[0]!));
  }, 120_000);
});
