import { describe, expect, it } from 'vitest';
import {
  dedupeQualifiedNames,
  detectLanguage,
  isGeneratedContent,
  isGeneratedPath,
  isSupported,
  isTestPath,
  makeSymbolKey,
  parseSymbolKey,
  rustExcludedDirs,
  supportLevelOf,
  symbolIdFromKey,
} from '../src/index.js';

describe('symbol key', () => {
  it('round-trips and has no line numbers', () => {
    const parts = { path: 'a/b.py', kind: 'method', qualifiedName: 'Svc.end_order', signature: '' };
    const key = makeSymbolKey(parts);
    expect(key).toBe('a/b.py#method#Svc.end_order#');
    expect(parseSymbolKey(key)).toEqual(parts);
  });

  it('parses dedup suffix and java signatures', () => {
    expect(parseSymbolKey('a.py#function#f#2#')).toEqual({ path: 'a.py', kind: 'function', qualifiedName: 'f#2', signature: '' });
    expect(parseSymbolKey('A.java#method#A.f#(String,int)').signature).toBe('(String,int)');
  });

  it('id is 16 hex chars and stable', () => {
    const id = symbolIdFromKey('a.py#function#f#');
    expect(id).toMatch(/^[0-9a-f]{16}$/);
    expect(symbolIdFromKey('a.py#function#f#')).toBe(id);
  });

  it('dedupes repeated definitions in order', () => {
    const items = [1, 2, 3].map(() => ({ path: 'a.py', kind: 'function', qualifiedName: 'f', signature: '' }));
    expect(dedupeQualifiedNames(items).map((i) => i.qualifiedName)).toEqual(['f', 'f#2', 'f#3']);
  });
});

describe('language', () => {
  it('detects languages and support levels', () => {
    expect(detectLanguage('x/y.py')).toBe('python');
    expect(supportLevelOf('python', 'x/y.py')).toBe('full');
    expect(detectLanguage('A.java')).toBe('java');
    expect(supportLevelOf('java', 'A.java')).toBe('none');
    expect(supportLevelOf('go', 'internal/a.go')).toBe('full');
    expect(supportLevelOf('go', 'vendor/x/a.go')).toBe('none');
    expect(supportLevelOf('go', 'backend/vendor/x/a.go')).toBe('none');
    expect(supportLevelOf('go', 'pkg/testdata/a.go')).toBe('none');
    expect(supportLevelOf('go', 'pkg/vendors/a.go')).toBe('full');
    expect(detectLanguage('README.md')).toBe('unknown');
  });

  it('excludes Rust target/ and vendor/ only next to a Cargo.toml', () => {
    expect(detectLanguage('src/lib.rs')).toBe('rust');
    const excluded = rustExcludedDirs(['Cargo.toml', 'crates/core/Cargo.toml', 'crates/core/src/lib.rs']);
    expect([...excluded].sort()).toEqual(['crates/core/target', 'crates/core/vendor', 'target', 'vendor']);
    expect(supportLevelOf('rust', 'crates/core/target/debug/x.rs', excluded)).toBe('none');
    expect(supportLevelOf('rust', 'vendor/dep/src/lib.rs', excluded)).toBe('none');
    expect(supportLevelOf('rust', 'crates/core/src/vendor/mod.rs', excluded)).toBe('full');
    expect(supportLevelOf('rust', 'crates/core/src/target.rs', excluded)).toBe('full');
    expect(supportLevelOf('rust', 'vendor/dep/src/lib.rs')).toBe('full');
    expect(isSupported('target/debug/x.rs')).toBe(true);
  });
});

describe('classify', () => {
  it('detects test code', () => {
    expect(isTestPath('tests/test_a.py')).toBe(true);
    expect(isTestPath('server/tests/helpers.py')).toBe(true);
    expect(isTestPath('pkg/test_x.py')).toBe(true);
    expect(isTestPath('pkg/x_test.py')).toBe(true);
    expect(isTestPath('conftest.py')).toBe(true);
    expect(isTestPath('pkg/testing.py')).toBe(false);
    expect(isTestPath('pkg/contest.py')).toBe(false);
    expect(isTestPath('e2e/flow.py', { testGlobs: ['e2e/**'] })).toBe(true);
  });

  it('detects generated code', () => {
    expect(isGeneratedPath('api/foo_pb2.py')).toBe(true);
    expect(isGeneratedPath('api/foo.py')).toBe(false);
    expect(isGeneratedPath('gen/x.py', { generatedGlobs: ['gen/**'] })).toBe(true);
  });

  it('detects Go test and generated code', () => {
    expect(isTestPath('internal/order/service_test.go')).toBe(true);
    expect(isTestPath('internal/order/service.go')).toBe(false);
    expect(isTestPath('internal/order/testing.go')).toBe(false);
    expect(isGeneratedPath('api/order.pb.go')).toBe(true);
    expect(isGeneratedPath('order.pb.go')).toBe(true);
    expect(isGeneratedPath('api/order.pb.gw.go')).toBe(true);
    expect(isGeneratedPath('db/models_gen.go')).toBe(true);
    expect(isGeneratedPath('db/models.go')).toBe(false);
  });

  it('detects Go generated code by the header line', () => {
    expect(isGeneratedContent('go', '// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage x\n')).toBe(true);
    expect(isGeneratedContent('go', '// Copyright 2024\n\n// Code generated by mockgen. DO NOT EDIT.\r\npackage x\n')).toBe(true);
    expect(isGeneratedContent('go', '// Code generated by hand, edit freely.\npackage x\n')).toBe(false);
    expect(isGeneratedContent('go', '  // Code generated by x. DO NOT EDIT.\n')).toBe(false);
    expect(isGeneratedContent('go', `${'// filler\n'.repeat(300)}// Code generated by x. DO NOT EDIT.\n`)).toBe(false);
    expect(isGeneratedContent('python', '// Code generated by x. DO NOT EDIT.\n')).toBe(false);
  });

  it('detects Rust test and generated code', () => {
    expect(isTestPath('crates/core/tests/it.rs')).toBe(true);
    expect(isTestPath('crates/core/benches/speed.rs')).toBe(true);
    expect(isTestPath('crates/core/src/lib.rs')).toBe(false);
    expect(isTestPath('benches/speed.py')).toBe(false);
    expect(isTestPath('benches/speed_bench.go')).toBe(false);
    expect(isGeneratedContent('rust', '// @generated by prost-build\n\npub struct A;\n')).toBe(true);
    expect(isGeneratedContent('rust', '// @generated\npub struct A;\n')).toBe(true);
    expect(isGeneratedContent('rust', '// Code generated by sqlc. DO NOT EDIT\npub struct A;\n')).toBe(true);
    expect(isGeneratedContent('rust', '// This file is @generated by prost-build.\npub struct A;\n')).toBe(true);
    expect(isGeneratedContent('rust', 'const S: &str = "@generated";\n')).toBe(false);
    expect(isGeneratedContent('rust', '// generated by hand\npub struct A;\n')).toBe(false);
    expect(isGeneratedContent('go', '// @generated\npackage x\n')).toBe(false);
  });
});
